-- ============================================================================
-- 1. Основні SELECT запити
-- ============================================================================

-- Завдання 1.1:
-- Отримати всі записи з таблиці customers.
-- Бізнес-логіка: Повний огляд клієнтської бази для CRM-системи та перевірки контактів.
SELECT
    *
FROM customers AS c;

-- Завдання 1.2:
-- Вивести тільки назви товарів і їхні ціни з таблиці products.
-- Бізнес-логіка: Формування базового прайс-листа для сайту без технічних полів.
SELECT
    p.product_name,
    p.unit_price
FROM products AS p;

-- Завдання 1.3:
-- Показати контактні дані всіх співробітників (ім'я, прізвище, телефон, email).
-- Бізнес-логіка: Створення внутрішнього довідника для оперативної комунікації між відділами.
SELECT
    e.first_name,
    e.last_name,
    e.phone,
    e.email
FROM employees AS e;


-- ============================================================================
-- 2. Прості умови WHERE
-- ============================================================================

-- Завдання 2.1:
-- Знайти всіх клієнтів з міста Київ.
-- Бізнес-логіка: Таргетинг промо-кампанії експрес-доставки для мешканців столиці.
SELECT
    *
FROM customers AS c
WHERE c.city = 'Київ';

-- Завдання 2.2:
-- Вивести товари, які коштують більше 25000 грн.
-- Бізнес-логіка: Сегментація преміальної техніки для аналізу маржинальності.
SELECT
    p.product_name,
    p.unit_price
FROM products AS p
WHERE p.unit_price > 25000;

-- Завдання 2.3:
-- Показати всі замовлення зі статусом 'delivered'.
-- Бізнес-логіка: Фіксація виконаних замовлень для розрахунку виторгу та бонусів.
SELECT
    *
FROM orders AS o
WHERE o.order_status = 'delivered';

-- Завдання 2.4:
-- Знайти співробітників, які працюють у відділі продажів.
-- Бізнес-логіка: Визначення персоналу з продажу для розподілу плану реалізації.
SELECT
    *
FROM employees AS e
WHERE e.title ILIKE '%продаж%';


-- ============================================================================
-- 3. Базове сортування ORDER BY
-- ============================================================================

-- Завдання 3.1:
-- Відсортувати товари за зростанням ціни.
-- Бізнес-логіка: Фільтр цін від дешевих до дорогих для покупців з обмеженим бюджетом.
SELECT
    *
FROM products AS p
ORDER BY p.unit_price;

-- Завдання 3.2:
-- Показати клієнтів в алфавітному порядку за іменем контактної особи.
-- Бізнес-логіка: Алфавітне впорядкування бази для швидкого пошуку клієнта оператором.
SELECT
    c.customer_id,
    c.contact_name,
    c.city,
    c.phone
FROM customers AS c
ORDER BY c.contact_name;

-- Завдання 3.3:
-- Вивести замовлення від найновіших до найстаріших.
-- Бізнес-логіка: Хронологічний моніторинг операційної діяльності та динаміки продажів.
SELECT
    *
FROM orders AS o
ORDER BY o.order_date DESC, o.order_id DESC;


-- ============================================================================
-- 4. Обмеження результатів LIMIT
-- ============================================================================

-- Завдання 4.1:
-- Показати перші 10 найдорожчих товарів.
-- Бізнес-логіка: Звіт топ-10 найкоштовніших активів магазину для складського контролю.
SELECT
    p.product_id,
    p.product_name,
    p.unit_price
FROM products AS p
ORDER BY p.unit_price DESC
LIMIT 10;

-- Завдання 4.2:
-- Вивести 5 останніх замовлень (за датою).
-- Бізнес-логіка: Моніторинг свіжих замовлень черги для термінової передачі на склад.
SELECT
    o.order_id,
    o.order_date,
    o.customer_id,
    o.order_status,
    o.ship_city,
    o.freight
FROM orders AS o
ORDER BY o.order_date DESC, o.order_id DESC
LIMIT 5;

-- Завдання 4.2 (Бонус, JOIN):
-- Деталізовані позиції останніх замовлень із назвами товарів та адресою.
-- Бізнес-логіка: Складський маніфест з інформацією про товари останніх доставок.
SELECT
    c.contact_name,
    p.product_name,
    oi.quantity,
    oi.unit_price,
    o.order_id,
    o.order_date,
    CONCAT('м. ', o.ship_city, ', ', o.ship_address) AS full_address
FROM orders AS o
INNER JOIN customers AS c
    ON o.customer_id = c.customer_id
INNER JOIN order_items AS oi
    ON o.order_id = oi.order_id
INNER JOIN products AS p
    ON oi.product_id = p.product_id
ORDER BY o.order_date DESC, o.order_id DESC
LIMIT 5;

-- Завдання 4.3:
-- Отримати перших 8 клієнтів в алфавітному порядку.
-- Бізнес-логіка: Початкова сторінка списку клієнтів для першого екрана CRM.
SELECT
    c.customer_id,
    c.contact_name,
    c.city
FROM customers AS c
ORDER BY c.contact_name
LIMIT 8;
